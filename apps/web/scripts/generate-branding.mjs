import { readFileSync, writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';

import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ts from 'typescript';

const logoSource = new URL('../src/components/branding/ludora-logo.tsx', import.meta.url);
const themeSource = new URL('../src/config/theme.ts', import.meta.url);
const publicDirectory = new URL('../public/', import.meta.url);
const generatedComment = '<!-- Generated by pnpm branding:generate. Edit ludora-logo.tsx. -->';

// Compile the two source modules so the generator can run with Node and TypeScript.
const hooks = registerHooks({
  load(url, context, nextLoad) {
    if (url !== logoSource.href && url !== themeSource.href) {
      return nextLoad(url, context);
    }

    const { outputText } = ts.transpileModule(readFileSync(new URL(url), 'utf8'), {
      compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext },
    });

    return { format: 'module', shortCircuit: true, source: outputText };
  },
});

const { LudoraLogo, LudoraMark } = await import(logoSource.href);
const { FAVICON_BY_THEME } = await import(themeSource.href);
hooks.deregister();

for (const [theme, faviconPath] of Object.entries(FAVICON_BY_THEME)) {
  const favicon = renderToStaticMarkup(createElement(LudoraMark, { theme, variant: 'favicon' }));
  const logo = renderToStaticMarkup(createElement(LudoraLogo, { theme }));

  writeFileSync(new URL(faviconPath.slice(1), publicDirectory), `${generatedComment}\n${favicon}\n`);
  writeFileSync(
    new URL(`branding/ludora-logo-${theme}.svg`, publicDirectory),
    `${generatedComment}\n${logo}\n`,
  );
}
